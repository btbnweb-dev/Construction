import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const width of [320, 390, 640, 768, 1024, 1440]) {
  test('responsive page and assets at ' + width + 'px', async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto('/')
    await expect(page).toHaveTitle('NOMAD Build — Санаанаас бодит орон зай.')
    await expect(page.locator('html')).toHaveAttribute('lang', 'mn')
    await expect(page.locator('.service-row')).toHaveCount(4)
    await expect(page.locator('.project-card')).toHaveCount(4)
    await expect(page.locator('.process-step')).toHaveCount(4)
    await expect(page.locator('.review')).toHaveCount(3)
    for (const id of ['home', 'services', 'projects', 'about', 'process', 'contact']) {
      await page.locator('#' + id).scrollIntoViewIfNeeded()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
    await page.locator('footer').scrollIntoViewIfNeeded()
    await page.evaluate(() => document.fonts.ready)
    await expect.poll(() => page.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
    expect(await page.locator('a[href^="#"]').evaluateAll(links => links.every(link => document.querySelector(link.getAttribute('href')!) !== null))).toBe(true)
    expect(await page.locator('a[target="_blank"]').evaluateAll(links => links.every(link => link.getAttribute('rel')?.includes('noopener') && link.getAttribute('href')?.startsWith('https://')))).toBe(true)
    expect(await page.locator('h1,h2,h3,p,button,input,select,textarea').evaluateAll(nodes => nodes.filter(node => node.clientWidth > 0 && node.scrollWidth > node.clientWidth + 2).map(node => node.textContent))).toEqual([])
    await expect(page.locator('.contact-phone')).toHaveAttribute('href', 'tel:+97677002020')
    await expect(page.locator('.contact-item a[href^="mailto:"]')).toHaveAttribute('href', 'mailto:hello@nomadbuild.example')
    await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
    await page.screenshot({ path: 'test-results/nomad-' + width + '-full.png', fullPage: true })
    await page.screenshot({ path: 'test-results/nomad-' + width + '-hero.png' })
    expect(errors).toEqual([])
  })
}

