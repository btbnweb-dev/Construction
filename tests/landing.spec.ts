test('project dialogs work on a short screen, trap and restore focus', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  for (let i = 0; i < 4; i++) {
    const card = page.locator('.project-card').nth(i)
    const source = await card.locator('img').getAttribute('src')
    await card.click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await expect(dialog.locator('.dialog-photo')).toHaveAttribute('src', source!)
    const box = await dialog.boundingBox()
    expect(box!.width).toBeLessThanOrEqual(320)
    expect(box!.height).toBeLessThanOrEqual(568)
    expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.locator('.button')).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.locator('.dialog-close')).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(card).toBeFocused()
    expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  }
})

test('form explains invalid input, focuses errors and confirms a local demo only', async ({ page }) => {
  await page.goto('/')
  const posts: string[] = []
  page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
  const form = page.locator('form')
  await form.getByRole('button', { name: 'Илгээх', exact: true }).click()
  await expect(page.locator('#quote-name')).toBeFocused()
  await expect(page.locator('.field-error')).toHaveCount(4)
  await page.locator('#quote-name').fill('Тест хэрэглэгч')
  await page.locator('#quote-phone').fill('123')
  await page.locator('#quote-email').fill('invalid@')
  await page.locator('#quote-type').selectOption('renovation')
  await page.locator('#quote-message').fill('80 м² орон сууцны иж бүрэн засвар хийлгэх хүсэлтэй.')
  await form.getByRole('button', { name: 'Илгээх', exact: true }).click()
  await expect(page.locator('#quote-phone')).toBeFocused()
  await expect(page.locator('.field-error')).toHaveCount(2)
  await page.locator('#quote-phone').fill('+976 9911 2233')
  await page.locator('#quote-email').fill('test@example.com')
  await form.getByRole('button', { name: 'Илгээх', exact: true }).click()
  await expect(page.locator('.success-message')).toContainText('хүсэлтийг илгээгээгүй')
  await expect(page.locator('.field-error')).toHaveCount(0)
  expect(posts).toEqual([])
  await form.getByRole('button', { name: 'Шинээр бөглөх' }).click()
  await expect(page.locator('#quote-name')).toHaveValue('')
  await expect(page.locator('#quote-type')).toHaveValue('')
  await expect(page.locator('#quote-name')).toBeFocused()
  await expect(page.locator('.success-message')).toHaveCount(0)
})

